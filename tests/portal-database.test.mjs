  currentOwner=owner;await login(owner,'hub@groupmf.com.br');
  assert.equal((await db.query('select * from public.spatial_portal_documents')).rows.length,0);
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  await assert.rejects(save(2),/STALE_VERSION/);
  await db.exec('reset role; set role anon');
  await assert.rejects(db.query('select * from public.spatial_portal_documents'),/permission denied/);
  await assert.rejects(save(0),/permission denied/);
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  assert.equal((await db.query('select * from public.spatial_portal_members')).rows.length,0);
  await db.exec("insert into storage.objects(bucket_id,name) values ('existing-public-bucket','unrelated-asset')");
  assert.equal((await db.query('select * from storage.objects')).rows.length,1);
